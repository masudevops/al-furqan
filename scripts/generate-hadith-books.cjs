#!/usr/bin/env node
// Regenerates src/lib/hadith-books-data.ts from fawazahmed0/hadith-api (Unlicense) — the dataset UmmahAPI wraps.
// Book names and membership are copied from the source; nothing is classified or renamed here.
// Usage: node scripts/generate-hadith-books.cjs
const fs = require("node:fs");
const path = require("node:path");

const SOURCE = "https://cdn.jsdelivr.net/gh/fawazahmed0/hadith-api@1/info.json";
const OUTPUT = path.join(__dirname, "..", "src", "lib", "hadith-books-data.ts");

async function main() {
  const response = await fetch(SOURCE);
  if (!response.ok) throw new Error(`hadith-api info.json request failed: ${response.status}`);
  const info = await response.json();
  const index = {};
  for (const [collection, { metadata, hadiths }] of Object.entries(info)) {
    const names = Object.entries(metadata.sections).filter(([number, name]) => Number(number) > 0 && name.trim());
    // A single book is the whole collection (e.g. Forty Hadith); there is nothing to browse by.
    if (names.length < 2) continue;
    const counts = new Map();
    const runs = [];
    let unassigned = 0;
    let previousBook = null;
    for (const hadith of [...hadiths].sort((a, b) => a.hadithnumber - b.hadithnumber)) {
      const book = hadith.reference?.book ?? 0;
      if (!book) unassigned += 1;
      else {
        counts.set(book, (counts.get(book) ?? 0) + 1);
        // A run only spans consecutive records of one book, so a Hadith without a book is never attributed to a neighbour's.
        if (book === previousBook) runs.at(-1)[1] = hadith.hadithnumber;
        else runs.push([hadith.hadithnumber, hadith.hadithnumber, book]);
      }
      previousBook = book;
    }
    index[collection] = {
      books: names.map(([number, name]) => [Number(number), name.trim(), counts.get(Number(number)) ?? 0]).filter(([, , count]) => count > 0).sort((a, b) => a[0] - b[0]),
      runs,
      unassigned,
    };
  }
  const body = `// Generated by scripts/generate-hadith-books.cjs from fawazahmed0/hadith-api@1 info.json (Unlicense). Do not edit by hand.
// Book names, book numbers and which book each Hadith belongs to are the source's own; Hadith without a book reference are counted in \`unassigned\`.

export type HadithBookIndex = {
  /** [book number, name as given by the source, Hadith count] */
  books: Array<[number, string, number]>;
  /** [first Hadith number, last Hadith number, book number] for consecutive Hadith in the same book */
  runs: Array<[number, number, number]>;
  unassigned: number;
};

export const HADITH_BOOKS: Record<string, HadithBookIndex> = ${JSON.stringify(index)};
`;
  fs.writeFileSync(OUTPUT, body);
  for (const [collection, value] of Object.entries(index)) console.log(`${collection}: ${value.books.length} books, ${value.runs.length} runs, ${value.unassigned} without a book`);
}

main().catch((error) => { console.error(error); process.exit(1); });
